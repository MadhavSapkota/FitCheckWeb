"""Publishing history, watchdog and alerts for the daily blog automation. Standard library only.

Commands (python -m seo_agent.publish_monitor <command>):
  record    append this run's outcome to data/publish-history.json (+ PUBLISH-HISTORY.md). Idempotent per run id.
  watchdog  decide, for the current Chicago day, whether to do nothing / dispatch a retry / alert. Never publishes itself.
  alert     open (once per day) a GitHub issue and, if SMTP secrets exist, send an email.

Safety: this module never writes an article. Retries are workflow dispatches of the normal daily-seo workflow, which keeps
its own protections (concurrency group, 1-article/day limit counted in Chicago time, re-check after rebase), so a retry can
never create a second article for the same day.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import smtplib
import subprocess
import sys
import urllib.request
from datetime import date, datetime, time, timedelta, timezone
from email.message import EmailMessage
from pathlib import Path
from zoneinfo import ZoneInfo

CHICAGO = ZoneInfo("America/Chicago")
DATA = Path(__file__).resolve().parent.parent / "data"
HISTORY = DATA / "publish-history.json"
HISTORY_MD = DATA / "PUBLISH-HISTORY.md"
STATE = DATA / "state.json"
BASE_URL = "https://fitcheck-fashion.com"
WORKFLOW = "daily-seo.yml"

PRIMARY = time(18, 0)                       # cron-job.org fires the daily run at 18:00 Chicago
GRACE = timedelta(minutes=30)               # primary has until 18:30 before the watchdog considers it missed
RETRY_AT = (time(20, 0), time(22, 0))       # retry #1 / #2 for "no candidate passed" or failed runs
MAX_ATTEMPTS = 1 + len(RETRY_AT)
# Skips that retrying cannot fix: the owner must act (still retried once at 20:00 in case it was transient).
ATTENTION = re.compile(r"No keyword volume provider|Keyword Planner unavailable|spending limit|ANTHROPIC_API_KEY|fatal", re.I)


# --------------------------------------------------------------------------------------------------------------------
# history
# --------------------------------------------------------------------------------------------------------------------
def classify(decision: str, job_ok: bool) -> str:
    d = (decision or "").lower()
    if not job_ok:
        return "failed"
    if d.startswith("published"):
        return "published"
    if "daily article limit" in d:
        return "skipped_limit"
    if "no candidate passed" in d or "no keyword met" in d:
        return "skipped_no_candidate"
    return "skipped_other" if d.startswith("skip") else "no_article"


def load_history(path: Path = HISTORY) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else []


def build_record(state: dict, *, day: str, run_id: str, run_url: str, job_ok: bool, verify_outcome: str,
                 commit_sha: str, now: datetime | None = None) -> dict:
    runs = state.get("runs") or []
    decision = runs[-1]["decision"] if runs else ""
    outcome = classify(decision, job_ok)
    rec = {"date": day, "recorded_at": (now or datetime.now(timezone.utc)).isoformat(timespec="seconds"),
           "run_id": str(run_id), "run_url": run_url, "outcome": outcome, "decision": decision[:400],
           "keyword": None, "title": None, "slug": None, "url": None, "commit": None, "deploy": "n/a"}
    if outcome == "published":
        m = re.search(r"published /blog/([a-z0-9-]+)/ for '([^']+)'", decision)
        slug = m.group(1) if m else None
        art = (state.get("articles") or {}).get(slug or "", {})
        rec.update(slug=slug, keyword=m.group(2) if m else art.get("keyword"), title=art.get("title") or art.get("h1"),
                   url=f"{BASE_URL}/blog/{slug}/" if slug else None, commit=commit_sha or None,
                   deploy={"success": "live", "failure": "NOT_LIVE", "cancelled": "NOT_LIVE"}.get(verify_outcome, "not_checked"))
    return rec


def add_record(history: list[dict], rec: dict) -> list[dict]:
    history = [h for h in history if h.get("run_id") != rec["run_id"]]  # idempotent: a re-run replaces, never duplicates
    history.append(rec)
    return sorted(history, key=lambda h: (h["date"], h["recorded_at"]))


def render_md(history: list[dict]) -> str:
    out = ["# Publishing history", "",
           "One row per daily-seo run (newest first). Generated by `seo_agent.publish_monitor record`; do not edit by hand.", "",
           "| Date (Chicago) | Outcome | Title | Keyword | URL | Commit | Deploy | Run |", "|---|---|---|---|---|---|---|---|"]
    for h in reversed(history):
        title = (h.get("title") or h.get("decision") or "")[:90].replace("|", "/")
        out.append(f"| {h['date']} | {h['outcome']} | {title} | {h.get('keyword') or ''} | {h.get('url') or ''} | "
                   f"{(h.get('commit') or '')[:7]} | {h.get('deploy')} | [run]({h.get('run_url') or ''}) |")
    return "\n".join(out) + "\n"


def cmd_record(a: argparse.Namespace) -> int:
    """Two phases so a failed/half-finished run can never push stray files: --emit builds the record from this run's local
    state.json; the workflow then resets to origin/master and --apply adds that record to the committed history."""
    if a.apply:
        rec = json.loads(Path(a.apply).read_text(encoding="utf-8"))
        hist = add_record(load_history(), rec)
        HISTORY.write_text(json.dumps(hist, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        HISTORY_MD.write_text(render_md(hist), encoding="utf-8")
        print("recorded:", json.dumps(rec, ensure_ascii=False))
        return 0
    state = json.loads(STATE.read_text(encoding="utf-8"))
    rec = build_record(state, day=os.environ["SEO_AGENT_TODAY"], run_id=os.environ["GITHUB_RUN_ID"],
                       run_url=os.environ.get("RUN_URL", ""), job_ok=os.environ.get("AGENT_OUTCOME") == "success"
                       and os.environ.get("COMMIT_OUTCOME", "success") in ("success", "skipped"),
                       verify_outcome=os.environ.get("VERIFY_OUTCOME", ""), commit_sha=os.environ.get("ARTICLE_COMMIT", ""))
    Path(a.emit).write_text(json.dumps(rec, ensure_ascii=False), encoding="utf-8")
    print("emitted:", json.dumps(rec, ensure_ascii=False))
    return 0


# --------------------------------------------------------------------------------------------------------------------
# watchdog decision (pure function, unit tested)
# --------------------------------------------------------------------------------------------------------------------
def chicago(dt: datetime) -> datetime:
    return dt.astimezone(CHICAGO)


def decide(day: date, now: datetime, history: list[dict], runs: list[dict]) -> dict:
    """Return {"action": ok|wait|dispatch|alert|none, "reason": str, ...}.

    `runs` = daily-seo runs on master that started on `day` at/after 17:30 Chicago (dicts: created(datetime aware),
    status(queued|in_progress|completed), conclusion). History rows for `day` say what each finished run produced.
    """
    n = chicago(now)
    today = n.date()
    rows = [h for h in history if h["date"] == str(day)]
    if any(h["outcome"] == "published" for h in rows):
        return {"action": "ok", "reason": "article published"}
    if day > today:
        return {"action": "none", "reason": "future day"}
    is_today = day == today
    t = n.time()
    if is_today and t < (datetime.combine(day, PRIMARY) + GRACE).time():
        return {"action": "none", "reason": "before 18:30 Chicago: primary scheduler still has time"}
    if any(r["status"] != "completed" for r in runs):
        return {"action": "wait", "reason": "a run is still in progress"}
    attempts = len(runs)
    last = rows[-1] if rows else None
    last_run_ok = bool(runs) and runs[-1].get("conclusion") == "success"
    if attempts == 0:
        if not is_today:
            return {"action": "alert", "reason": f"{day}: the 6 PM run never started (primary scheduler did not fire)"}
        return {"action": "dispatch", "reason": "primary scheduler did not start a run by 18:30 Chicago", "attempt": 1}
    why = (last or {}).get("decision") or (f"workflow run ended with '{runs[-1].get('conclusion')}'" if not last_run_ok else "no history row recorded")
    if last_run_ok and last and last["outcome"] == "skipped_limit":
        return {"action": "alert", "reason": f"limit message but no article recorded for {day}: {why}"}
    if attempts < MAX_ATTEMPTS and is_today and t >= RETRY_AT[attempts - 1]:
        return {"action": "dispatch", "reason": f"retry #{attempts}: {why[:200]}", "attempt": attempts + 1}
    if attempts >= MAX_ATTEMPTS or not is_today or t >= RETRY_AT[-1]:
        return {"action": "alert", "reason": f"no article published for {day} after {attempts} attempt(s): {why}"}
    attn = bool(ATTENTION.search(why))
    return {"action": "alert" if attn else "none", "reason": why if attn else f"waiting for retry window ({why[:120]})"}


# --------------------------------------------------------------------------------------------------------------------
# GitHub / network helpers
# --------------------------------------------------------------------------------------------------------------------
def gh(*args: str, check: bool = True) -> str:
    p = subprocess.run(["gh", *args], capture_output=True, text=True)
    if check and p.returncode:
        raise RuntimeError(f"gh {' '.join(args[:3])} failed: {p.stderr.strip()[:300]}")
    return p.stdout


def fetch_runs(repo: str, day: date) -> list[dict]:
    since = datetime.combine(day, time(17, 30), tzinfo=CHICAGO)
    raw = json.loads(gh("run", "list", "-R", repo, "--workflow", WORKFLOW, "--branch", "master", "-L", "60",
                        "--json", "createdAt,status,conclusion,databaseId,event"))
    out = []
    for r in raw:
        created = datetime.fromisoformat(r["createdAt"].replace("Z", "+00:00"))
        if created >= since and created < since + timedelta(hours=24) and r["event"] in ("workflow_dispatch", "schedule"):
            out.append({"created": created, "status": r["status"], "conclusion": r["conclusion"], "id": r["databaseId"]})
    return sorted(out, key=lambda r: r["created"])


def url_live(url: str) -> bool:
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "fitcheck-publish-monitor"}), timeout=30) as r:
            return r.status == 200 and "canonical" in r.read(400_000).decode("utf-8", "ignore")
    except Exception:  # noqa: BLE001
        return False


def send_email(subject: str, body: str) -> str:
    host, user, pw, to = (os.environ.get(k, "") for k in ("SMTP_HOST", "SMTP_USER", "SMTP_PASSWORD", "ALERT_EMAIL_TO"))
    if not (host and user and pw and to):
        return "email skipped: SMTP_HOST/SMTP_USER/SMTP_PASSWORD/ALERT_EMAIL_TO secrets not set"
    msg = EmailMessage()
    msg["Subject"], msg["From"], msg["To"] = subject, os.environ.get("SMTP_FROM") or user, to
    msg.set_content(body)
    port = int(os.environ.get("SMTP_PORT") or 465)
    try:
        if port == 465:
            with smtplib.SMTP_SSL(host, port, timeout=30) as s:
                s.login(user, pw)
                s.send_message(msg)
        else:
            with smtplib.SMTP(host, port, timeout=30) as s:
                s.starttls()
                s.login(user, pw)
                s.send_message(msg)
        return "email sent"
    except Exception as e:  # noqa: BLE001 - the GitHub issue (which GitHub also emails) is the primary channel
        return f"email FAILED: {type(e).__name__}: {e}"


def raise_alert(repo: str, day: date, reason: str, dry: bool) -> None:
    title = f"[publish-alert] {day}: no blog article published"
    body = (f"**{reason}**\n\nDate (Chicago): {day}\nHistory: `seo-agent/data/PUBLISH-HISTORY.md`\n"
            f"Runs: https://github.com/{repo}/actions/workflows/{WORKFLOW}\n\n"
            "Fix the cause (for example an expired Google Ads token, exhausted Claude credit, or no eligible keyword), then run "
            "the *Daily SEO agent* workflow manually. The issue closes itself after the next article is published.")
    if dry:
        print(f"[dry-run] would open issue '{title}': {reason}")
        return
    found = gh("issue", "list", "-R", repo, "--state", "all", "--search", f'"{title}" in:title', "--json", "number", "--jq", ".[0].number").strip()
    if found:
        print(f"alert already raised (issue #{found}); not repeating")
        return
    gh("label", "create", "publish-alert", "-R", repo, "--color", "d93f0b", "--force", check=False)
    gh("issue", "create", "-R", repo, "--title", title, "--body", body, "--label", "publish-alert")
    print("issue opened;", send_email(title, body))


def close_resolved(repo: str, history: list[dict], dry: bool) -> None:
    pub = {h["date"]: h for h in history if h["outcome"] == "published"}
    if not pub or dry:
        return
    latest = max(pub.values(), key=lambda h: h["date"])
    for n in gh("issue", "list", "-R", repo, "--label", "publish-alert", "--state", "open", "--json", "number", "--jq", ".[].number", check=False).split():
        gh("issue", "close", n, "-R", repo, "-c", f"Resolved: published {latest['url']} on {latest['date']}.", check=False)


def cmd_watchdog(a: argparse.Namespace) -> int:
    repo = os.environ.get("GITHUB_REPOSITORY", "MadhavSapkota/FitCheckWeb")
    now = datetime.fromisoformat(a.now) if a.now else datetime.now(timezone.utc)
    history = load_history()
    today = chicago(now).date()
    rc = 0
    for day in (today - timedelta(days=1), today):
        runs = fetch_runs(repo, day) if not a.fixture_runs else json.loads(Path(a.fixture_runs).read_text())
        for r in runs:
            if isinstance(r["created"], str):
                r["created"] = datetime.fromisoformat(r["created"])
        d = decide(day, now, history, runs)
        print(f"{day}: {d['action']} - {d['reason']}")
        pub = next((h for h in history if h["date"] == str(day) and h["outcome"] == "published"), None)
        if d["action"] == "ok" and pub and pub.get("url") and not a.no_network and not url_live(pub["url"]):
            raise_alert(repo, day, f"article recorded as published but {pub['url']} is not live (HTTP 200 + canonical check failed)", a.dry_run)
            rc = 1
        elif d["action"] == "dispatch" and day == today:
            if a.dry_run:
                print(f"[dry-run] would dispatch {WORKFLOW} on master")
            else:
                gh("workflow", "run", WORKFLOW, "-R", repo, "--ref", "master")
        elif d["action"] == "alert":
            raise_alert(repo, day, d["reason"], a.dry_run)
            rc = 1
    close_resolved(repo, history, a.dry_run)
    return rc


def backfill(state: dict) -> list[dict]:
    """One-time seed of the history from state.json's run log (Chicago dates; commit/run ids unknown)."""
    out: list[dict] = []
    for r in state.get("runs") or []:
        at = datetime.fromisoformat(r["at"])
        one = {"runs": [r], "articles": state.get("articles") or {}}
        rec = build_record(one, day=str(chicago(at).date()), run_id=f"backfill-{r['at']}", run_url="", job_ok=not r.get("errors"),
                           verify_outcome="", commit_sha="", now=at)
        if rec["outcome"] == "published":
            rec["deploy"] = "not_checked (before monitoring)"
        out = add_record(out, rec)
    return out


def cmd_backfill(a: argparse.Namespace) -> int:
    if HISTORY.exists():
        print("history already exists; nothing to do")
        return 0
    hist = backfill(json.loads(STATE.read_text(encoding="utf-8")))
    HISTORY.write_text(json.dumps(hist, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    HISTORY_MD.write_text(render_md(hist), encoding="utf-8")
    print(f"seeded {len(hist)} rows")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("command", choices=["record", "watchdog", "backfill"])
    ap.add_argument("--dry-run", action="store_true", help="watchdog: print decisions, dispatch/alert nothing")
    ap.add_argument("--now", help="watchdog: ISO timestamp with offset to evaluate (testing)")
    ap.add_argument("--fixture-runs", help="watchdog: JSON file of runs instead of the GitHub API (testing)")
    ap.add_argument("--no-network", action="store_true")
    ap.add_argument("--emit", help="record: write this run's record (JSON) to this path")
    ap.add_argument("--apply", help="record: add the record in this JSON file to the committed history")
    a = ap.parse_args(argv)
    return {"record": cmd_record, "watchdog": cmd_watchdog, "backfill": cmd_backfill}[a.command](a)


if __name__ == "__main__":
    sys.exit(main())
